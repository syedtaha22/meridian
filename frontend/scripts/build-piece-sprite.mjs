// Builds src/lib/piece-sprite.ts from the piece drawings in src/assets/pieces.
//
// The drawings, one for each black piece, were created by Claude. Each white piece is its
// black drawing with lighter shading colors, and the white knight has a dark eye.
//
// Usage: node scripts/build-piece-sprite.mjs

/* global console */
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')

// The symbols to write: the key of the symbol, and the drawing it comes from.
const PIECES = {
  bk: 'bking',
  bp: 'bpawn',
  bn: 'bknight',
  bb: 'bbishop',
  br: 'brook',
  bq: 'bqueen',
  wk: 'bking',
  wp: 'bpawn',
  wn: 'bknight',
  wb: 'bbishop',
  wr: 'brook',
  wq: 'bqueen',
}

// The six shading colors of a white piece, from the base layer to the top highlight.
const WHITE_SHADING = ['#b0b0b0', '#cbcbcb', '#e2e2e2', '#f0f0f0', '#fafafa', '#ffffff']

// The color of the eye of the white knight.
const WHITE_EYE = '#5c5c5c'

function symbolMarkup(drawing, key) {
  const source = readFileSync(join(root, 'src/assets/pieces', `${drawing}.svg`), 'utf8')
  let inner = source.replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '')

  // A white piece takes the shading colors of white, in the order of the layers.
  if (key.startsWith('w')) {
    let layer = 0
    inner = inner.replace(/fill="#[0-9a-f]{6}"/gi, (match) => {
      if (layer >= WHITE_SHADING.length) return match
      return `fill="${WHITE_SHADING[layer++]}"`
    })
    if (layer !== WHITE_SHADING.length) {
      throw new Error(
        `${drawing}.svg has ${layer} shading layers, expected ${WHITE_SHADING.length}`,
      )
    }

    // The eye is the second shape in the first shading layer. It goes above the shading and
    // below the border.
    if (drawing === 'bknight') {
      const firstLayer = source.match(/<path fill="#[0-9a-f]{6}"[^>]*? d="([^"]+)"/i)
      const eye = firstLayer && firstLayer[1].match(/M[^M]+/g)[1]
      if (!eye) throw new Error('bknight.svg has no eye shape')
      inner = inner.replace(
        '<use xlink:href="#s" fill="none"',
        `<path fill="${WHITE_EYE}" d="${eye.trim()}"/><use xlink:href="#s" fill="none"`,
      )
    }
  }

  // Unique ids per piece, and the modern spelling of the references.
  const ids = [...inner.matchAll(/\bid="([^"]+)"/g)].map((m) => m[1])
  let out = inner.replace(/xlink:href/g, 'href')
  for (const id of ids) {
    out = out
      .replaceAll(`id="${id}"`, `id="chess-${key}-${id}"`)
      .replaceAll(`href="#${id}"`, `href="#chess-${key}-${id}"`)
      .replaceAll(`url(#${id})`, `url(#chess-${key}-${id})`)
  }
  return out
}

/**
 * Splits after spaces and tag ends so that no line is longer than `width`.
 */
function chunks(text, width = 70) {
  const words = text.split(/(?<=[ >])/)
  const lines = []
  let line = ''
  for (const word of words) {
    if (line.length + word.length > width && line !== '') {
      lines.push(line)
      line = ''
    }
    line += word
  }
  if (line !== '') lines.push(line)
  return lines
}

const entries = []
for (const [key, drawing] of Object.entries(PIECES)) {
  const lines = chunks(symbolMarkup(drawing, key))
    .map((l) => `    '${l.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}',`)
    .join('\n')
  entries.push(`  ${key}: [\n${lines}\n  ].join(''),`)
}

writeFileSync(
  join(root, 'src/lib/piece-sprite.ts'),
  `// Generated by scripts/build-piece-sprite.mjs from src/assets/pieces. Do not edit.
//
// One SVG symbol per piece. The key is the color (w or b) and then the kind (k, p, n, b, r, q).
export type PieceKey =
  | 'wk' | 'wp' | 'wn' | 'wb' | 'wr' | 'wq'
  | 'bk' | 'bp' | 'bn' | 'bb' | 'br' | 'bq'

export const PIECE_SYMBOLS: Record<PieceKey, string> = {
${entries.join('\n')}
}
`,
)
console.log('wrote src/lib/piece-sprite.ts')
