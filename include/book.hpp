#pragma once

#include <cstddef>
#include <cstdint>
#include <optional>
#include <span>

#include "position.hpp"
#include "types.hpp"

namespace chess {

    /**
     * One move of the opening book in one position.
     */
    struct BookEntry {
        uint64_t key;     ///< Hash of the position, as `Position::key` gives it.
        uint16_t move;    ///< The move, as `Move::data` holds it.
        uint16_t weight;  ///< Relative probability of the move among the moves of the position.
        int16_t score;    ///< Centipawns for the side to move, from the search that built the book.
    };

    /**
     * A move taken from the book.
     */
    struct BookChoice {
        Move move;
        int score = 0;  ///< Centipawns for the side to move.
        int depth = 0;  ///< Depth of the search that scored the move.
    };

    /**
     * @brief A set of opening moves, looked up by position.
     *
     * The built-in book is generated by `tools/build_book` and compiled into the library. A
     * position that is in the book has one to several moves, chosen at random by weight.
     */
    class Book {
    public:
        /**
         * The book compiled into the library.
         */
        static const Book &builtin();

        /**
         * @brief Creates a book over sorted entries.
         *
         * @param entries Entries ordered by key. The span has to outlive the book.
         * @param depth Depth of the search that scored the entries.
         */
        Book(std::span<const BookEntry> entries, int depth) noexcept;

        /**
         * Number of entries.
         */
        size_t size() const noexcept {
            return entries_.size();
        }

        /**
         * The entries of one position, ordered by weight, largest first.
         */
        std::span<const BookEntry> find(uint64_t key) const noexcept;

        /**
         * @brief Chooses a move for a position.
         *
         * @param pos Position to move in.
         * @param random Any 64-bit random number; the same number gives the same move.
         * @return A legal move by weight, or nothing when the position is not in the book.
         */
        std::optional<BookChoice> pick(const Position &pos, uint64_t random) const;

    private:
        std::span<const BookEntry> entries_;
        int depth_;
    };

}  // namespace chess
